void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
#if LAB_MODE == LAB_SPWM
    if (hadc->Instance != ADC1)
    {
        return;
    }

    adc_last = HAL_ADC_GetValue(hadc);

    uint32_t ma = ma_percent;
    if (ma > 100U)
    {
        ma = 100U;
    }

    /* 입력 사인파를 정규화하고 변조지수 적용 */
    int32_t reference =
        (((int32_t)adc_last - INPUT_CENTER_COUNTS) * REF_ONE)
        / INPUT_PEAK_COUNTS;

    reference = (reference * (int32_t)ma) / 100L;

    if (reference > REF_ONE)
    {
        reference = REF_ONE;
    }
    else if (reference < -REF_ONE)
    {
        reference = -REF_ONE;
    }

    /* 하드웨어 삼각 카운터와 비교할 CCR 값 */
    uint32_t level = (uint32_t)(reference + REF_ONE);
    uint32_t arr = __HAL_TIM_GET_AUTORELOAD(&htim1);
    uint32_t compare = (arr * level) / 65536UL;

    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, compare);

    /* DAC: 원본 입력 또는 변조된 기준파 */
    dac_last = (dac_show_input != 0U)
               ? adc_last
               : (4095UL * level) / 65536UL;

    Lab_CheckHAL(HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_1,
                                 DAC_ALIGN_12B_R, dac_last));
#else
    (void)hadc;
#endif
}

